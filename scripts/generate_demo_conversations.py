"""Generate docs/DEMO_CONVERSATIONS.md by running the 5 real-DB demo scripts."""

from __future__ import annotations

import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from recipelens.orchestrator.chat import ChatSession
from scripts.chat import run_script

DEMO_SCRIPTS = [
    (
        "Conversation 1: Multi-Turn Search with Refinements (Dairy & Gluten Constraints)",
        ROOT / "scripts" / "demo_scripts" / "conv1_search_dairy.txt",
    ),
    (
        "Conversation 2: Recipe Analytics — Exact Count and Percentage (Garlic AND Onion)",
        ROOT / "scripts" / "demo_scripts" / "conv2_garlic_onion.txt",
    ),
    (
        "Conversation 3: Recipe Analytics — Ranked by Step Count (Tomato Recipes with Fewest Steps)",
        ROOT / "scripts" / "demo_scripts" / "conv3_tomato_steps.txt",
    ),
    (
        "Conversation 4: Explainable Pantry Matching with Follow-Up Exclusion",
        ROOT / "scripts" / "demo_scripts" / "conv4_pantry_match.txt",
    ),
    (
        "Conversation 5: Constraint Violation Handling — No-Match Case with Explanations",
        ROOT / "scripts" / "demo_scripts" / "conv5_no_match.txt",
    ),
]


def main() -> None:
    output_lines: list[str] = [
        "# RecipeLens Demo Conversations (Phase 4A)",
        "",
        "This document contains verbatim transcripts from five real-database conversational sessions generated using `scripts/chat.py --script` over the 122,971-recipe Recipe Box corpus. No answers were edited by hand or generated by an LLM.",
        "",
    ]

    print("Initializing RecipeLens full engine...", file=sys.stderr)
    session = ChatSession.build()
    print("Services ready. Running scripts...", file=sys.stderr)

    for title, script_path in DEMO_SCRIPTS:
        print(f"Running {title}...", file=sys.stderr)
        output_lines.append(f"## {title}\n")
        output_lines.append("```text")

        # Capture output
        buf = io.StringIO()
        old_stdout = sys.stdout
        sys.stdout = buf
        try:
            # Reset state between conversations
            session.state = session.state.reset()
            run_script(session, script_path)
        finally:
            sys.stdout = old_stdout

        transcript = buf.getvalue().strip()
        output_lines.append(transcript)
        output_lines.append("```\n")

    dest = ROOT / "docs" / "DEMO_CONVERSATIONS.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(output_lines).rstrip() + "\n", encoding="utf-8")
    print(f"Successfully generated {dest}", file=sys.stderr)


if __name__ == "__main__":
    main()
