"""Append three live-database Task 3 transcripts to docs/DEMO_CONVERSATIONS.md."""

from __future__ import annotations

import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from recipelens.orchestrator.chat import ChatSession
from recipelens.orchestrator.state import SessionState
from scripts.chat import run_script

MARKER = "## Stage 2: Task 3 substitution transcripts"
CASES = (
    (
        "Banana bread without eggs",
        ROOT / "scripts" / "demo_scripts" / "sub1_banana_bread_no_eggs.txt",
    ),
    (
        "Cream replaced without dairy in a pasta recipe",
        ROOT / "scripts" / "demo_scripts" / "sub2_cream_pasta_no_dairy.txt",
    ),
    (
        "Conflicting evidence: cream in tomato cream pasta",
        ROOT / "scripts" / "demo_scripts" / "sub3_conflicting_evidence.txt",
    ),
)


def main() -> None:
    print("Initializing RecipeLens against the local full database and index...", file=sys.stderr)
    session = ChatSession.build()
    generated = [
        MARKER,
        "",
        "The following transcripts were generated by replaying the scripts below against the local SQLite database and full vector index. No transcript text was edited by hand.",
        "",
    ]
    for title, script_path in CASES:
        print(f"Running {title}...", file=sys.stderr)
        session.state = SessionState.reset()
        capture = io.StringIO()
        previous_stdout = sys.stdout
        sys.stdout = capture
        try:
            run_script(session, script_path)
        finally:
            sys.stdout = previous_stdout
        generated.extend((f"### {title}", "", "```text", capture.getvalue().strip(), "```", ""))

    document = ROOT / "docs" / "DEMO_CONVERSATIONS.md"
    existing = document.read_text(encoding="utf-8") if document.exists() else ""
    base = existing.split(MARKER, maxsplit=1)[0].rstrip()
    document.write_text(base + "\n\n" + "\n".join(generated).rstrip() + "\n", encoding="utf-8")
    print(f"Wrote {document}", file=sys.stderr)


if __name__ == "__main__":
    main()
